// --- Detection patterns ---

// AI agent patterns (in commit message or author/committer fields)
const AI_AGENT_PATTERNS = {
  coAuthorPatterns: [
    /co-authored-by:.*\bclaude\b/i,
    /co-authored-by:.*\banthropic\b/i,
    /co-authored-by:.*\bcopilot\b/i,
    /co-authored-by:.*\bcursor\b/i,
    /co-authored-by:.*\bdevin\b/i,
    /co-authored-by:.*\bcognition\b/i,
    /co-authored-by:.*\bcody\b/i,
    /co-authored-by:.*\bsourcegraph\b/i,
    /co-authored-by:.*\baider\b/i,
    /co-authored-by:.*\bsweep\b/i,
    /co-authored-by:.*\btabnine\b/i,
    /co-authored-by:.*\bamazon-q\b/i,
    /co-authored-by:.*\bwindsurf\b/i,
    /co-authored-by:.*\bcodeium\b/i,
  ],
  authorPatterns: [
    /devin-ai\[bot\]/i,
    /sweep-ai\[bot\]/i,
    /coderabbit.*\[bot\]/i,
    /ellipsis-dev\[bot\]/i,
    /sourcery-ai\[bot\]/i,
    /codeflash-ai\[bot\]/i,
  ],
  messagePatterns: [
    /\bgenerated by (?:claude|copilot|cursor|devin|cody|aider)\b/i,
  ],
};

// Traditional bot patterns (automated but not AI)
const BOT_PATTERNS = {
  authorPatterns: [
    /dependabot\[bot\]/i,
    /renovate\[bot\]/i,
    /github-actions\[bot\]/i,
    /greenkeeper\[bot\]/i,
    /snyk-bot/i,
    /codecov\[bot\]/i,
    /netlify\[bot\]/i,
    /vercel\[bot\]/i,
    /semantic-release-bot/i,
    /\[bot\]@users\.noreply\.github\.com/i,
    /web-flow@users\.noreply\.github\.com/i, // GitHub merge commits via web UI — not a bot per se, but automated
  ],
  loginPatterns: [
    /\[bot\]$/i,
  ],
};

type CommitClass = "ai-agent" | "traditional-bot" | "human";
type AITool = "claude" | "copilot" | "devin" | "cody" | "aider" | "sweep" | "cursor" | "coderabbit" | "sourcery" | "other-ai";

interface RawCommit {
  sha?: string;
  commit?: {
    message?: string;
    author?: { email?: string; date?: string };
    committer?: { email?: string; date?: string };
  };
  author?: { login?: string };
  committer?: { login?: string };
}

function classifyCommit(commit: RawCommit): { classification: CommitClass; aiTool?: AITool } {
  const message = commit.commit?.message || "";
  const authorLogin = commit.author?.login || "";
  const authorEmail = commit.commit?.author?.email || "";
  const committerLogin = commit.committer?.login || "";
  const committerEmail = commit.commit?.committer?.email || "";

  const allText = `${message}\n${authorLogin}\n${authorEmail}\n${committerLogin}\n${committerEmail}`;

  // 1. Check AI agent patterns
  for (const pattern of AI_AGENT_PATTERNS.coAuthorPatterns) {
    if (pattern.test(message)) {
      return { classification: "ai-agent", aiTool: detectAITool(message, authorLogin) };
    }
  }
  for (const pattern of AI_AGENT_PATTERNS.authorPatterns) {
    if (pattern.test(authorLogin) || pattern.test(committerLogin)) {
      return { classification: "ai-agent", aiTool: detectAITool(allText, authorLogin) };
    }
  }
  for (const pattern of AI_AGENT_PATTERNS.messagePatterns) {
    if (pattern.test(message)) {
      return { classification: "ai-agent", aiTool: detectAITool(message, authorLogin) };
    }
  }

  // 2. Check traditional bot patterns
  for (const pattern of BOT_PATTERNS.authorPatterns) {
    if (pattern.test(authorEmail) || pattern.test(committerEmail) ||
        pattern.test(authorLogin) || pattern.test(committerLogin)) {
      return { classification: "traditional-bot" };
    }
  }
  for (const pattern of BOT_PATTERNS.loginPatterns) {
    if (pattern.test(authorLogin) || pattern.test(committerLogin)) {
      // Check it's not already caught as AI
      return { classification: "traditional-bot" };
    }
  }

  // 3. Default: human
  return { classification: "human" };
}

function detectAITool(text: string, login: string): AITool {
  const lower = text.toLowerCase() + " " + login.toLowerCase();
  if (/claude|anthropic/.test(lower)) return "claude";
  if (/copilot/.test(lower)) return "copilot";
  if (/devin|cognition/.test(lower)) return "devin";
  if (/cody|sourcegraph/.test(lower)) return "cody";
  if (/aider/.test(lower)) return "aider";
  if (/sweep/.test(lower)) return "sweep";
  if (/cursor/.test(lower)) return "cursor";
  if (/coderabbit/.test(lower)) return "coderabbit";
  if (/sourcery/.test(lower)) return "sourcery";
  return "other-ai";
}

// --- Windows ---
const WINDOWS = [30, 90, 365] as const;
type WindowDays = (typeof WINDOWS)[number];

function sinceDate(days: number): string {
  return new Date(Date.now() - days * 24 * 60 * 60 * 1000).toISOString();
}

const MIN_COMMITS_THRESHOLD = 5;
const MAX_COMMITS_PER_WINDOW = 500;

