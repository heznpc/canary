// --- Types ---
interface WindowACR {
  window: WindowDays;
  totalCommits: number;
  commitsFetched: number;
  aiAgentCommits: number;
  botCommits: number;
  humanCommits: number;
  acr: number;
  acrPercent: string;
  botRate: number;
  botRatePercent: string;
  automationRate: number; // (ai + bot) / total
  automationPercent: string;
  aiToolBreakdown: Record<string, number>;
  excluded: boolean;
}

interface RepoACRResult {
  repo: string;
  group: "user" | "reference";
  subgroup?: "ai-adjacent" | "traditional";
  windows: WindowACR[];
  sampleAICommits: { sha: string; tool: string; snippet: string }[];
}

// --- API ---
let apiCallCount = 0;

async function apiFetch(url: string): Promise<Response> {
  apiCallCount++;
  const res = await fetch(url, { headers });
  if (res.status === 403 || res.status === 429) {
    const reset = res.headers.get("x-ratelimit-reset");
    const waitSec = reset ? Math.max(0, parseInt(reset) - Math.floor(Date.now() / 1000)) : 60;
    console.warn(`  Rate limited (${apiCallCount} calls). Waiting ${waitSec}s...`);
    await new Promise((r) => setTimeout(r, waitSec * 1000 + 1000));
    apiCallCount++;
    return fetch(url, { headers });
  }
  return res;
}

async function fetchCommits(
  owner: string, name: string, since: string, max: number,
): Promise<RawCommit[]> {
  const commits: RawCommit[] = [];
  let page = 1;
  while (commits.length < max) {
    const url =
      `https://api.github.com/repos/${owner}/${name}/commits` +
      `?since=${since}&per_page=100&page=${page}`;
    const res = await apiFetch(url);
    if (!res.ok) break;
    const data = await res.json();
    if (!Array.isArray(data) || data.length === 0) break;
    for (const c of data) {
      commits.push(c);
      if (commits.length >= max) break;
    }
    if (data.length < 100) break;
    page++;
  }
  return commits;
}

async function computeACR(
  repo: string,
  group: "user" | "reference",
  subgroup?: "ai-adjacent" | "traditional",
): Promise<RepoACRResult | null> {
  const [owner, name] = repo.split("/");
  if (!owner || !name) return null;

  process.stdout.write(`  ${repo} ...`);

  const windows: WindowACR[] = [];
  const sampleAICommits: { sha: string; tool: string; snippet: string }[] = [];

  for (const days of WINDOWS) {
    const since = sinceDate(days);
    const commits = await fetchCommits(owner, name, since, MAX_COMMITS_PER_WINDOW);

    if (commits.length < MIN_COMMITS_THRESHOLD) {
      windows.push({
        window: days, totalCommits: commits.length, commitsFetched: commits.length,
        aiAgentCommits: 0, botCommits: 0, humanCommits: 0,
        acr: 0, acrPercent: "0.0%",
        botRate: 0, botRatePercent: "0.0%",
        automationRate: 0, automationPercent: "0.0%",
        aiToolBreakdown: {}, excluded: true,
      });
      continue;
    }

    let aiCount = 0, botCount = 0, humanCount = 0;
    const toolBreakdown: Record<string, number> = {};

    for (const c of commits) {
      const { classification, aiTool } = classifyCommit(c);
      if (classification === "ai-agent") {
        aiCount++;
        const tool = aiTool || "other-ai";
        toolBreakdown[tool] = (toolBreakdown[tool] || 0) + 1;
        // Collect samples (up to 5 per repo)
        if (sampleAICommits.length < 5) {
          const msg = (c.commit?.message || "").split("\n")[0].slice(0, 80);
          sampleAICommits.push({ sha: (c.sha ?? "").slice(0, 7), tool, snippet: msg });
        }
      } else if (classification === "traditional-bot") {
        botCount++;
      } else {
        humanCount++;
      }
    }

    const total = commits.length;
    const acr = total > 0 ? aiCount / total : 0;
    const botRate = total > 0 ? botCount / total : 0;
    const automationRate = total > 0 ? (aiCount + botCount) / total : 0;

    windows.push({
      window: days,
      totalCommits: total,
      commitsFetched: total,
      aiAgentCommits: aiCount,
      botCommits: botCount,
      humanCommits: humanCount,
      acr,
      acrPercent: (acr * 100).toFixed(1) + "%",
      botRate,
      botRatePercent: (botRate * 100).toFixed(1) + "%",
      automationRate,
      automationPercent: (automationRate * 100).toFixed(1) + "%",
      aiToolBreakdown: toolBreakdown,
      excluded: false,
    });
  }

  const w90 = windows.find((w) => w.window === 90);
  const summary = w90 && !w90.excluded
    ? `AI=${w90.acrPercent} Bot=${w90.botRatePercent} Human=${(100 - w90.acr * 100 - w90.botRate * 100).toFixed(0)}%`
    : "excluded";
  console.log(` ${summary}`);

  return { repo, group, subgroup, windows, sampleAICommits };
}

async function getUserRepos(username: string): Promise<string[]> {
  const repos: string[] = [];
  let page = 1;
  while (page <= 5) {
    const res = await apiFetch(
      `https://api.github.com/users/${username}/repos?per_page=100&sort=updated&page=${page}`,
    );
    if (!res.ok) break;
    const data = await res.json();
    if (!Array.isArray(data) || data.length === 0) break;
    for (const r of data) {
      if (!r.fork && !r.archived) repos.push(r.full_name);
    }
    page++;
  }
  return repos;
}

// --- Main ---
async function main() {
  const username = process.argv[2] || "heznpc";

  console.log(`\n=== ACR Experiment (Agent-Authored Commit Ratio) ===`);
  console.log(`Windows: ${WINDOWS.join("d, ")}d`);
  console.log(`Max commits per window: ${MAX_COMMITS_PER_WINDOW}\n`);

  // 1. User repos
  console.log(`Fetching repos for ${username}...`);
  const userRepos = await getUserRepos(username);
  console.log(`Found ${userRepos.length} repos\n`);

  console.log("--- User repos ---");
  const userResults: RepoACRResult[] = [];
  for (const repo of userRepos) {
    const r = await computeACR(repo, "user");
    if (r) userResults.push(r);
  }

  // 2. Reference repos
  console.log("\n--- Reference repos (AI-adjacent) ---");
  const refResults: RepoACRResult[] = [];
  for (const { repo, subgroup } of REFERENCE_REPOS.filter((r) => r.subgroup === "ai-adjacent")) {
    const r = await computeACR(repo, "reference", subgroup);
    if (r) refResults.push(r);
  }
  console.log("\n--- Reference repos (Traditional) ---");
  for (const { repo, subgroup } of REFERENCE_REPOS.filter((r) => r.subgroup === "traditional")) {
    const r = await computeACR(repo, "reference", subgroup);
    if (r) refResults.push(r);
  }

  // 3. Helpers
  const mean = (arr: number[]) => (arr.length ? arr.reduce((a, b) => a + b, 0) / arr.length : 0);
  const median = (arr: number[]) => {
    const s = [...arr].sort((a, b) => a - b);
    const m = Math.floor(s.length / 2);
    return s.length === 0 ? 0 : s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
  };

  const all = [...userResults, ...refResults];

  // 4. Summary table
  console.log("\n\n========================================");
  console.log("    ACR RESULTS");
  console.log("========================================\n");

  const subgroups = [
    { label: "User", filter: (r: RepoACRResult) => r.group === "user" },
    { label: "AI-adjacent", filter: (r: RepoACRResult) => r.subgroup === "ai-adjacent" },
    { label: "Traditional", filter: (r: RepoACRResult) => r.subgroup === "traditional" },
    { label: "All Reference", filter: (r: RepoACRResult) => r.group === "reference" },
  ];

  for (const days of WINDOWS) {
    console.log(`\n--- ${days}-day window ---`);
    console.log(
      ["Group".padEnd(16), "n".padStart(3),
       "mean ACR".padStart(10), "median ACR".padStart(12),
       "mean Bot".padStart(10), "mean Auto".padStart(11),
      ].join(" | "),
    );
    console.log("-".repeat(75));

    for (const sg of subgroups) {
      const repos = all.filter(sg.filter);
      const windowData = repos
        .map((r) => r.windows.find((w) => w.window === days)!)
        .filter((w) => !w.excluded);

      const acrs = windowData.map((w) => w.acr);
      const bots = windowData.map((w) => w.botRate);
      const autos = windowData.map((w) => w.automationRate);

      console.log([
        sg.label.padEnd(16), String(windowData.length).padStart(3),
        ((mean(acrs) * 100).toFixed(1) + "%").padStart(10),
        ((median(acrs) * 100).toFixed(1) + "%").padStart(12),
        ((mean(bots) * 100).toFixed(1) + "%").padStart(10),
        ((mean(autos) * 100).toFixed(1) + "%").padStart(11),
      ].join(" | "));
    }
  }

  // 5. Per-repo detail (repos with AI commits)
  const reposWithAI = all.filter((r) =>
    r.windows.some((w) => !w.excluded && w.aiAgentCommits > 0),
  );

  if (reposWithAI.length > 0) {
    console.log("\n\n--- Repos with detected AI-agent commits ---\n");
    console.log(
      ["Repo".padEnd(40), "30d ACR".padStart(8), "90d ACR".padStart(8), "365d ACR".padStart(9),
       "AI tool(s)".padEnd(20),
      ].join(" | "),
    );
    console.log("-".repeat(95));

    for (const r of reposWithAI.sort((a, b) => {
      const a90 = a.windows.find((w) => w.window === 90);
      const b90 = b.windows.find((w) => w.window === 90);
      return (b90?.acr ?? 0) - (a90?.acr ?? 0);
    })) {
      const vals = WINDOWS.map((days) => {
        const w = r.windows.find((w) => w.window === days)!;
        return w.excluded ? "(exc)".padStart(days === 365 ? 9 : 8) : w.acrPercent.padStart(days === 365 ? 9 : 8);
      }).join(" | ");

      const tools = [...new Set(
        r.windows.flatMap((w) => Object.keys(w.aiToolBreakdown)),
      )].join(", ");

      console.log(`${r.repo.padEnd(40)} | ${vals} | ${tools}`);
    }

    // Sample commits
    console.log("\n--- Sample AI-agent commits ---\n");
    for (const r of reposWithAI) {
      if (r.sampleAICommits.length === 0) continue;
      console.log(`  ${r.repo}:`);
      for (const s of r.sampleAICommits) {
        console.log(`    [${s.tool}] ${s.sha} ${s.snippet}`);
      }
    }
  }

  // 6. AI tool distribution across all repos
  console.log("\n--- AI Tool Distribution (all repos, 90d) ---\n");
  const toolTotals: Record<string, number> = {};
  for (const r of all) {
    const w90 = r.windows.find((w) => w.window === 90);
    if (!w90 || w90.excluded) continue;
    for (const [tool, count] of Object.entries(w90.aiToolBreakdown)) {
      toolTotals[tool] = (toolTotals[tool] || 0) + count;
    }
  }
  const sortedTools = Object.entries(toolTotals).sort((a, b) => b[1] - a[1]);
  for (const [tool, count] of sortedTools) {
    console.log(`  ${tool}: ${count} commits`);
  }

  // 7. Save
  const outputPath = new URL("../paper/acr-results.json", import.meta.url).pathname;
  await writeFile(
    outputPath,
    JSON.stringify({
      timestamp: new Date().toISOString(),
      windows: [...WINDOWS],
      maxCommitsPerWindow: MAX_COMMITS_PER_WINDOW,
      minCommitsThreshold: MIN_COMMITS_THRESHOLD,
      apiCallCount,
      userResults,
      refResults,
    }, null, 2),
  );
  console.log(`\nRaw data saved to ${outputPath}`);
  console.log(`Total API calls: ${apiCallCount}`);
}

main().catch(console.error);
