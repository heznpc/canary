/**
 * Agent-Authored Commit Ratio (ACR) Experiment
 *
 * Classifies commits into three categories:
 *   1. AI agent (Claude, Copilot, Devin, Cody, Aider, etc.)
 *   2. Traditional bot (Dependabot, Renovate, GitHub Actions, etc.)
 *   3. Human
 *
 * Measures ACR across 30d/90d/365d windows.
 *
 * This directly evidences metadatafication: if agents are authoring commits,
 * Git records are BY DEFINITION becoming automatically-generated metadata.
 *
 * Known limitation: many AI-assisted commits lack markers → this is a
 * conservative lower bound ("at least X% are agent-authored").
 *
 * Usage: npx tsx scripts/acr-experiment.ts [username]
 */

